        private static Model[] _models;

        /// <summary>取一种弹壳模型（首次调用时建网格；同一模型所有弹壳共用一份）。</summary>
        internal static Model Get(Kind kind)
        {
            if (kind == Kind.None) return null;
            if (_models == null)
            {
                _models = new[]
                {
                    Build(0, RifleVerts, RifleNorms, RifleUvs, RifleTris),
                    Build(1, PistolVerts, PistolNorms, PistolUvs, PistolTris),
                    Build(2, BigVerts, BigNorms, BigUvs, BigTris),
                };
            }
            return _models[(int)kind];
        }

        /// <summary>
        /// 逐武器选弹壳模型。出处 = <c>cstrike/cl_dlls/client.dll</c> 的 precache 串表（逐武器块里
        /// 紧跟 <c>models/p_&lt;武器&gt;.mdl</c> 的那一行）；<c>CsWeapons</c> 的 id 与短名同名同值。
        /// </summary>
        internal static Kind KindFor(string weaponId)
        {
            switch (weaponId)
            {
                // models/pshell.mdl（手枪）
                case CsWeapons.Glock18:
                case CsWeapons.Usp:
                case CsWeapons.P228:
                case CsWeapons.Deagle:
                case CsWeapons.FiveSeven:
                case CsWeapons.Elite:
                    return Kind.Pistol;
                // models/rshell_big.mdl（狙击）
                case CsWeapons.Awp:
                case CsWeapons.Scout:
                    return Kind.Big;
                // models/rshell.mdl（步枪 / 冲锋枪 / 机枪）
                case CsWeapons.Ak47:
                case CsWeapons.Aug:
                case CsWeapons.Famas:
                case CsWeapons.G3sg1:
                case CsWeapons.Galil:
                case CsWeapons.M249:
                case CsWeapons.M4A1:
                case CsWeapons.P90:
                case CsWeapons.Sg550:
                case CsWeapons.Sg552:
                case CsWeapons.Mp5:
                case CsWeapons.Tmp:
                case CsWeapons.Mac10:
                case CsWeapons.Ump45:
                    return Kind.Rifle;
                // m3 / xm1014 原版抛 models/shotgunshell.mdl —— 该件取不到，本表不含
                default:
                    return Kind.None;
            }
        }

        private static Model Build(int index, Vector3[] verts, Vector3[] norms,
            Vector2[] uvs, int[] tris)
        {
            var mesh = new Mesh
            {
                name = "Shell_" + SourceNames[index],
                vertices = verts,
                normals = norms,
                uv = uvs,
                triangles = tris,
                // 弹壳是 0.1 m 量级的小物件，Unity 默认视锥剔除会按错包围球把它裁掉，
                // 所以显式给一个覆盖全模型的包围球（半径取包围盒对角线一半）。
            };
            mesh.RecalculateBounds();
            return new Model
            {
                SourceName = SourceNames[index],
                Texture = TextureKeys[index],
                Size = Sizes[index],
                Verts = verts,
                Norms = norms,
                Uvs = uvs,
                Tris = tris,
                Mesh = mesh,
            };
        }
