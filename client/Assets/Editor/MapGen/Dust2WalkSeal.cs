        public static bool ApplyToFiles(string clientPath, string serverPath)
        {
            bool ok = true;
            ok &= ApplyToFile(clientPath);
            ok &= ApplyToFile(serverPath);
            return ok;
        }

        private static bool ApplyToFile(string path)
        {
            if (!File.Exists(path))
            {
                Debug.LogError($"{Tag} 产物缺失：{path}");
                return false;
            }

            byte[] bytes;
            try { bytes = File.ReadAllBytes(path); }
            catch (Exception e) { Debug.LogError($"{Tag} 读 {path} 失败：{e.Message}"); return false; }

            if (!TryLayout(bytes, out int width, out int depth, out int bitOffset, out int bitLength,
                           out int markerOffset, out int markerCount))
            {
                Debug.LogError($"{Tag} {path} 结构不符（不是本烘焙器的产物？）");
                return false;
            }

            var walkable = new bool[width * depth];
            for (int i = 0; i < walkable.Length; i++)
                walkable[i] = (bytes[bitOffset + (i >> 3)] & (1 << (i & 7))) != 0;

            bool[] next = Transform(walkable, width, depth, out int sealedCount, out int openedCount);
            for (int i = 0; i < walkable.Length; i++)
            {
                int k = bitOffset + (i >> 3);
                if (next[i]) bytes[k] |= (byte)(1 << (i & 7));
                else bytes[k] &= (byte)~(1 << (i & 7));
            }

            int moved = SnapMarkers(bytes, markerOffset, markerCount, next, width, depth);

            try { File.WriteAllBytes(path, bytes); }
            catch (Exception e) { Debug.LogError($"{Tag} 写 {path} 失败：{e.Message}"); return false; }

            int walk = 0;
            for (int i = 0; i < next.Length; i++) if (next[i]) walk++;
            Debug.Log($"{Tag} {path}：封 {sealedCount} 格 / 开 {openedCount} 格 / 标记点搬 {moved} 个 ⇒ 可走 {walk} 格");
            return true;
        }

        /// <summary>把位图里不在主分量（或不可走）的标记点搬到最近的主分量可走格（只改 x/z，保留 y）。</summary>
        private static int SnapMarkers(byte[] bytes, int markerOffset, int markerCount, bool[] walkable,
                                       int width, int depth)
        {
            if (markerCount <= 0 || markerOffset <= 0) return 0;

            // 位图与格坐标的换算参数
            float cell = BitConverter.ToSingle(bytes, 16);
            float ox = BitConverter.ToSingle(bytes, 20);
            float oz = BitConverter.ToSingle(bytes, 28);
            if (cell <= 0f)
            {
                Debug.LogError($"{Tag} CellSize={cell} 非法，跳过标记点搬移");
                return 0;
            }

            // 主分量
            Label(walkable, width, depth, out int[] comp, out int[] sizes);
            int main = Largest(sizes);

            int pos = markerOffset;
            int moved = 0;
            for (int m = 0; m < markerCount; m++)
            {
                int nameLen = BitConverter.ToInt32(bytes, pos);
                pos += 4;
                pos += nameLen;                        // 名字不动
                int xyzAt = pos;
                pos += 12;

                float x = BitConverter.ToSingle(bytes, xyzAt);
                float y = BitConverter.ToSingle(bytes, xyzAt + 4);
                float z = BitConverter.ToSingle(bytes, xyzAt + 8);

                int ix = Mathf.FloorToInt((x - ox) / cell);
                int iz = Mathf.FloorToInt((z - oz) / cell);
                if (In(width, depth, ix, iz) && walkable[iz * width + ix] && comp[iz * width + ix] == main)
                    continue;

                bool found = false;
                for (int r = 0; r <= MarkerSnapRadius && !found; r++)
                {
                    for (int dz = -r; dz <= r && !found; dz++)
                    {
                        for (int dx = -r; dx <= r && !found; dx++)
                        {
                            if (Math.Max(Math.Abs(dx), Math.Abs(dz)) != r) continue;
                            int nx = ix + dx, nz = iz + dz;
                            if (!In(width, depth, nx, nz)) continue;
                            int k = nz * width + nx;
                            if (!walkable[k] || comp[k] != main) continue;
                            BitConverter.GetBytes(ox + (nx + 0.5f) * cell).CopyTo(bytes, xyzAt);
                            BitConverter.GetBytes(oz + (nz + 0.5f) * cell).CopyTo(bytes, xyzAt + 8);
                            moved++;
                            found = true;
                            Debug.Log($"{Tag} 标记点 ({x:F1},{z:F1}) 不在主分量 ⇒ 搬到格 ({nx},{nz}) 世界 " +
                                      $"({ox + (nx + 0.5f) * cell:F1},{oz + (nz + 0.5f) * cell:F1})（y={y:F2} 保留）");
                        }
                    }
                }

                if (!found)
                    Debug.LogError($"{Tag} 标记点 ({x:F1},{z:F1}) 在 {MarkerSnapRadius} 格内找不到主分量可走格 —— 该点会是走不到的目标");
            }

            return moved;
        }

        private static bool In(int width, int depth, int ix, int iz)
            => ix >= 0 && iz >= 0 && ix < width && iz < depth;

        /// <summary>按 CloverMap v1 的字段顺序定位位图段与标记点段（与 <c>CloverMapProbe</c> 同源）。</summary>
        private static bool TryLayout(byte[] b, out int width, out int depth, out int bitOffset, out int bitLength,
                                      out int markerOffset, out int markerCount)
        {
            width = depth = bitLength = markerOffset = markerCount = 0;
            bitOffset = 0;
            if (b == null || b.Length < 64) return false;
            if (Encoding.ASCII.GetString(b, 0, 4) != "CLVM") return false;
            int version = BitConverter.ToUInt16(b, 4);
            int flags = BitConverter.ToUInt16(b, 6);
            if (version != 1) return false;
            if ((flags & 1) == 0) return false;

            width = (int)BitConverter.ToUInt32(b, 32);
            depth = (int)BitConverter.ToUInt32(b, 36);
            int colliders = (int)BitConverter.ToUInt32(b, 40);
            int spawns = (int)BitConverter.ToUInt32(b, 44);
            int nameLen = (int)BitConverter.ToUInt32(b, 48);
            if (width <= 0 || depth <= 0 || nameLen < 0) return false;

            bitOffset = 64 + nameLen;
            bitLength = (width * depth + 7) / 8;
            if (bitOffset + bitLength > b.Length) return false;

            markerOffset = bitOffset + bitLength + colliders * 24 + spawns * 12;
            if ((flags & 4) != 0)
            {
                if (markerOffset + 4 > b.Length) return false;
                markerCount = BitConverter.ToInt32(b, markerOffset);
                markerOffset += 4;
            }
            return true;
        }
    }
