        /// <summary>
        /// 把 <paramref name="walkable"/>（真 = 可走）收敛为单一连通分量：封掉非主分量、放开
        /// <see cref="OpenCells"/>、再把开门后仍孤立的格封掉。返回新的位图（不改入参）。
        /// </summary>
        public static bool[] Transform(bool[] walkable, int width, int depth,
                                       out int sealedCount, out int openedCount)
        {
            var result = (bool[])walkable.Clone();
            int total = width * depth;

            int sealedTable = 0;
            for (int i = 0; i < SealedCells.Length; i++)
            {
                var (ix, iz) = SealedCells[i];
                if (ix < 0 || iz < 0 || ix >= width || iz >= depth) continue;
                int k = iz * width + ix;
                if (result[k]) { result[k] = false; sealedTable++; }
            }

            int opened = 0;
            for (int i = 0; i < OpenCells.Length; i++)
            {
                var (ix, iz) = OpenCells[i];
                if (ix < 0 || iz < 0 || ix >= width || iz >= depth) continue;
                int k = iz * width + ix;
                if (!result[k]) { result[k] = true; opened++; }
            }

            Label(result, width, depth, out int[] comp, out int[] sizes);
            int main = Largest(sizes);
            int sealedExtra = 0;
            for (int i = 0; i < total; i++)
            {
                if (result[i] && comp[i] != main) { result[i] = false; sealedExtra++; }
            }

            Label(result, width, depth, out comp, out sizes);
            main = Largest(sizes);
            if (sizes.Length != 1)
                Debug.LogError($"{Tag} 变换后仍有 {sizes.Length} 个连通分量（主分量 {sizes[main]}）—— 位图没有收敛成单分量");

            sealedCount = sealedTable + sealedExtra;
            openedCount = opened;
            return result;
        }

        private static int Largest(int[] sizes)
        {
            int best = 0;
            for (int i = 1; i < sizes.Length; i++) if (sizes[i] > sizes[best]) best = i;
            return best;
        }

        /// <summary>8 邻接连通分量（对角要求两侧正交格都可走 —— 与引擎 <c>AStar</c> 的移动规则逐条一致）。</summary>
        private static void Label(bool[] walkable, int width, int depth, out int[] comp, out int[] sizes)
        {
            int total = width * depth;
            comp = new int[total];
            for (int i = 0; i < total; i++) comp[i] = -1;
            var list = new List<int>(64);
            var queue = new Queue<int>();

            for (int start = 0; start < total; start++)
            {
                if (!walkable[start] || comp[start] >= 0) continue;
                int cid = list.Count;
                int n = 0;
                comp[start] = cid;
                queue.Enqueue(start);
                while (queue.Count > 0)
                {
                    int cur = queue.Dequeue();
                    n++;
                    int cx = cur % width, cz = cur / width;
                    for (int k = 0; k < 8; k++)
                    {
                        int nx = cx + NeiDx[k], nz = cz + NeiDz[k];
                        if (nx < 0 || nz < 0 || nx >= width || nz >= depth) continue;
                        int ni = nz * width + nx;
                        if (!walkable[ni] || comp[ni] >= 0) continue;
                        if (NeiDx[k] != 0 && NeiDz[k] != 0)
                        {
                            if (!walkable[cz * width + nx] || !walkable[nz * width + cx]) continue;
                        }
                        comp[ni] = cid;
                        queue.Enqueue(ni);
                    }
                }
                list.Add(n);
            }

            sizes = list.ToArray();
        }

