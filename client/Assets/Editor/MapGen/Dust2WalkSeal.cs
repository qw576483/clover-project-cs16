    /// <summary>
    /// 烘焙后把可走位图收敛成**单一连通分量**，并把落在孤立格区里的标记点搬回主分量。
    ///
    /// <para><b>为什么需要</b>：引擎位图是**单层 2D**（一格一位、没有高度），而 de_dust2 是**多层**几何。
    /// 引擎的 2D 栅格化把"近垂直墙面"的格足迹封成阻挡 ⇒ 位图会出现**互不连通的格区**（实测 53 个分量、
    /// 939 格非主分量 = 17.7%）。对机器人寻路，非主分量意味着两类坏结果：
    /// ① 目标点落在里面（标记点）就**永远求不出路径**；② 自己走进去就被困住
    /// （引擎格子 A* 是纯 2D，不认高度）。</para>
    ///
    /// <para><b>两类格的处理口径</b>（判据见 <c>.ai-tmp/test/a51/</c> 的离线量法）：</para>
    /// <list type="number">
    /// <item><b>真不可达</b>（在图外/没有可站层/几何上没有同层入口）：封为阻挡。判据 = 它所在的
    /// **非主分量整体**在原版 de_dust2 雷达俯视图上是虚空像素（<c>a51-overview-fit.py</c>：主分量 397/400
    /// 抽样落在有画面像素，标定可信）；或者开门之后它仍然不在主分量里。</item>
    /// <item><b>烘焙漏掉</b>（在原版可玩区内，只是被 2D 格足迹误封）：把它的**入口格**放开
    /// （<see cref="OpenCells"/> 逐格登记，口径 = 该格有一个可站层，与相邻分量内格的可站层高差
    /// ≤ <c>CsConst.StepUpHeight</c> = 0.45 m，即运行时 <c>CsMap.TryStepUp</c> 的台阶口径）。
